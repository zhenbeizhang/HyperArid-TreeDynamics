from pathlib import Path
import json
import random
import math
import numpy as np
import torch
from models import unet
from datasets.tree_dataset import check_bands


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, allow_nan=False)+'\n', encoding='utf-8')


def seed_all(seed, threads=4):
    """Set generators and deterministic kernels for the recorded runtime environment."""
    random.seed(seed)
    np.random.seed(seed % 2**32)
    torch.manual_seed(seed)
    torch.set_num_threads(threads)
    torch.use_deterministic_algorithms(True)
    torch.backends.cudnn.benchmark = False


def load_config(path, bands=None):
    config = json.loads(Path(path).read_text(encoding='utf-8'))
    if bands is not None:
        config['bands'] = bands
    check_bands(config['bands'])
    for name in ['epochs', 'batch_size', 'threads']:
        if type(config[name]) is not int or config[name] <= 0:
            raise ValueError(f'{name} must be a positive integer.')
    if type(config['seed']) is not int or not 0 <= config['seed'] < 2**31:
        raise ValueError('seed must be an integer in [0, 2**31).')
    for name in ['learning_rate', 'weight_decay', 'threshold']:
        if not math.isfinite(config[name]):
            raise ValueError(f'{name} must be finite.')
    if config['learning_rate'] <= 0 or config['weight_decay'] < 0 or not 0 < config['threshold'] < 1:
        raise ValueError('Invalid optimizer or threshold setting.')
    a = config['augmentation']
    for name in ['hflip_probability', 'vflip_probability', 'color_jitter_probability']:
        if not 0 <= a[name] <= 1:
            raise ValueError(f'Invalid augmentation probability: {name}')
    if config['selection_metric'] != 'validation_pixel_iou':
        raise ValueError('This recipe selects checkpoints by validation_pixel_iou.')
    return config


def device_from(name):
    if name not in ['cpu', 'cuda']:
        raise ValueError('Choose cpu or cuda.')
    if name == 'cuda' and not torch.cuda.is_available():
        raise ValueError('CUDA requested but unavailable; use --device cpu.')
    return torch.device(name)


def load_checkpoint(path, device):
    """Restore a new-recipe checkpoint and enforce exact model parameter matching."""
    # weights_only avoids deserializing arbitrary Python objects from a checkpoint.
    payload = torch.load(path, map_location='cpu', weights_only=True)
    if not isinstance(payload, dict) or payload.get('format') != 'hyperarid-training-v1':
        raise ValueError('Expected a checkpoint generated by train.py. For the earlier tensor-only release use python -m tree_dynamics predict.')
    model = unet(n_channels=5)
    model.load_state_dict(payload['model'], strict=True)
    model.to(device).eval()
    return model, payload
